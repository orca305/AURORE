BEGIN;
CREATE TABLE user_bmark (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id bigint NOT NULL REFERENCES app_user(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
 legal_id bigint REFERENCES legal(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
 legal_prec_id bigint REFERENCES legal_prec(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
 del_yn boolean NOT NULL DEFAULT false,
 del_dttm timestamptz(0),
 del_id bigint,
 rgst_dttm timestamptz(0) NOT NULL DEFAULT date_trunc('second',CURRENT_TIMESTAMP),
 upt_dttm timestamptz(0) NOT NULL DEFAULT date_trunc('second',CURRENT_TIMESTAMP),
 CONSTRAINT ck_user_bmark_target CHECK (num_nonnulls(legal_id,legal_prec_id)=1),
 CONSTRAINT ck_user_bmark_deleted CHECK ((NOT del_yn AND del_dttm IS NULL AND del_id IS NULL) OR (del_yn AND del_dttm IS NOT NULL AND del_id IS NOT NULL AND del_id=user_id))
);
CREATE UNIQUE INDEX uq_user_bmark_active_legal ON user_bmark(user_id,legal_id) WHERE NOT del_yn AND legal_id IS NOT NULL;
CREATE UNIQUE INDEX uq_user_bmark_active_prec ON user_bmark(user_id,legal_prec_id) WHERE NOT del_yn AND legal_prec_id IS NOT NULL;
CREATE INDEX idx_user_bmark_user_date ON user_bmark(user_id,rgst_dttm DESC,id DESC);
COMMIT;
