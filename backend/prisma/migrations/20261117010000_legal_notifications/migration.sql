BEGIN;
ALTER TABLE legal_ver ADD CONSTRAINT uq_legal_ver_id_legal UNIQUE(id,legal_id);
ALTER TABLE legal_ver_rev ADD CONSTRAINT uq_legal_ver_rev_id_version UNIQUE(id,legal_ver_id);
CREATE TABLE legal_chg_evt (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 evt_key varchar(120) NOT NULL CONSTRAINT uq_legal_chg_evt_key UNIQUE,
 legal_id bigint NOT NULL REFERENCES legal(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
 legal_ver_id bigint NOT NULL,
 src_rev_id bigint NOT NULL,
 bf_rev_id bigint,
 evt_type_cd varchar(20) NOT NULL CHECK(evt_type_cd IN ('PROMULGATED','EFFECTIVE','CORRECTED')),
 scope_cd varchar(20) NOT NULL CHECK(scope_cd IN ('VERSION','PROVISIONS')),
 base_dt date NOT NULL,
 evt_dttm timestamptz(0) NOT NULL,
 evt_title varchar(300) NOT NULL CHECK(length(evt_title)>0),
 evt_cont text NOT NULL CHECK(length(evt_cont)>0),
 del_yn boolean NOT NULL DEFAULT false,del_dttm timestamptz(0),del_id bigint,
 rgst_dttm timestamptz(0) NOT NULL DEFAULT date_trunc('second',CURRENT_TIMESTAMP),
 FOREIGN KEY(legal_ver_id,legal_id) REFERENCES legal_ver(id,legal_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
 FOREIGN KEY(src_rev_id,legal_ver_id) REFERENCES legal_ver_rev(id,legal_ver_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
 FOREIGN KEY(bf_rev_id,legal_ver_id) REFERENCES legal_ver_rev(id,legal_ver_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
 CHECK ((evt_dttm AT TIME ZONE 'Asia/Seoul')::date=base_dt),
 CHECK ((evt_type_cd='CORRECTED' AND bf_rev_id IS NOT NULL AND bf_rev_id<>src_rev_id AND scope_cd='VERSION') OR (evt_type_cd<>'CORRECTED' AND bf_rev_id IS NULL)),
 CHECK(scope_cd<>'PROVISIONS' OR evt_type_cd='EFFECTIVE'),
 CHECK ((NOT del_yn AND del_dttm IS NULL AND del_id IS NULL) OR (del_yn AND del_dttm IS NOT NULL))
);
CREATE INDEX idx_legal_chg_evt_legal_date ON legal_chg_evt(legal_id,evt_dttm,id);
CREATE TABLE user_ntf (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id bigint NOT NULL REFERENCES app_user(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
 evt_id bigint NOT NULL REFERENCES legal_chg_evt(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
 read_dttm timestamptz(0),
 del_yn boolean NOT NULL DEFAULT false,del_dttm timestamptz(0),del_id bigint,
 rgst_dttm timestamptz(0) NOT NULL DEFAULT date_trunc('second',CURRENT_TIMESTAMP),
 CONSTRAINT uq_user_ntf_event UNIQUE(user_id,evt_id),
 CHECK ((NOT del_yn AND del_dttm IS NULL AND del_id IS NULL) OR (del_yn AND del_dttm IS NOT NULL AND del_id IS NOT NULL AND del_id=user_id))
);
CREATE INDEX idx_user_ntf_user_read ON user_ntf(user_id,del_yn,read_dttm,id DESC);
COMMIT;
